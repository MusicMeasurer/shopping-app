import { test, expect } from '@playwright/test'

test('browser E4: cancelled completion leaves items unchanged, permanent list persists with archive after reload', async ({ page }) => {
  await page.goto('/shopping-app/')
  const input = page.getByLabel('Что нужно купить? (можно несколько строк)')
  await input.fill('Молоко\nХлеб')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Молоко' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await page.getByRole('button', { name: 'Действия со списком', exact: true }).click()
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await page.getByRole('dialog', { name: 'Завершить список' }).getByRole('button', { name: 'Отмена' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await page.getByRole('button', { name: 'Действия со списком', exact: true }).click()
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await page.getByRole('button', { name: 'Завершить: отмеченные' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Продукты', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByText('Молоко')).toBeVisible()
  await expect(page.getByText('Хлеб')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByText('Молоко')).toBeVisible()
})

test('browser E4: oneoff completion disappears from active lists but survives in archive after reload', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByRole('button', { name: 'Новый список' }).click()
  await page.getByRole('dialog').getByLabel('Название списка').fill('Разовая проверка')
  await page.getByRole('dialog').getByLabel('Тип списка').selectOption('oneoff')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Создать список' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Разовая проверка' })).toBeVisible()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Сыр')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await page.getByRole('checkbox', { name: 'Сыр' }).click()
  await expect(page.getByRole('checkbox', { name: 'Сыр' })).toBeChecked()
  await page.getByRole('button', { name: 'Действия со списком', exact: true }).click()
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await page.getByRole('button', { name: 'Завершить: отмеченные' }).click()
  await expect(page.getByRole('button', { name: 'Разовая проверка', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Разовая проверка' })).toBeVisible()
  await expect(page.getByText('Сыр')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Разовая проверка' })).toBeVisible()
})

for (const kind of ['permanent', 'oneoff'] as const) {
  test(`partial archive keeps the ${kind} list and unmarked purchases after reload`, async ({ page }) => {
    await page.goto('/shopping-app/')
    await page.getByRole('button', { name: 'Новый список' }).click()
    const create = page.getByRole('dialog', { name: 'Создать список' })
    await create.getByLabel('Название списка').fill('Проверка покупок')
    await create.getByLabel('Тип списка').selectOption(kind)
    await create.getByRole('button', { name: 'Создать', exact: true }).click()
    await page.getByLabel('Что нужно купить?').fill('Сыр\nМолоко')
    await page.getByRole('button', { name: 'Добавить товар' }).click()
    const complete = page.getByRole('button', { name: 'Завершить список', exact: true })
    const partial = page.getByRole('menuitem', { name: 'Завершить покупки' })
    await complete.click()
    await expect(partial).toBeDisabled()
    await page.getByRole('button', { name: 'Закрыть меню', exact: true }).click({ position: { x: 4, y: 4 } })
    await page.getByRole('checkbox', { name: 'Сыр' }).check()
    await complete.click()
    await partial.click()
    const dialog = page.getByRole('dialog', { name: 'Завершить покупки' })
    await dialog.getByRole('button', { name: 'Отмена', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Сыр' })).toBeChecked()
    await complete.click()
    await partial.click()
    await dialog.getByRole('button', { name: 'Переместить в архив' }).click()
    await expect(page.getByRole('checkbox', { name: 'Сыр' })).toHaveCount(0)
    await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Проверка покупок', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeVisible()
    await page.getByRole('button', { name: /Архив,/ }).click()
    await expect(page.getByText('Сыр', { exact: true })).toBeVisible()
    await expect(page.getByText('Молоко', { exact: true })).toHaveCount(0)
  })
}
