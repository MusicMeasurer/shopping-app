import { test, expect } from '@playwright/test'

test('browser E4: cancelled completion leaves items unchanged, permanent list persists with archive after reload', async ({ page }) => {
  await page.goto('/shopping-app/')
  const input = page.getByLabel('Что нужно купить? (можно несколько строк)')
  await input.fill('Молоко\nХлеб')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Молоко' }).check()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Продукты', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByText('Молоко')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByText('Молоко')).toBeVisible()
})

test('browser E4: oneoff completion disappears from active lists but survives in archive after reload', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByRole('button', { name: 'Новый список' }).click()
  await page.getByRole('dialog').getByLabel('Название списка').fill('Разовая проверка')
  await page.getByRole('dialog').getByLabel('Тип списка').selectOption('oneoff')
  await page.getByRole('dialog').getByRole('button', { name: 'Создать', exact: true }).click()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Сыр')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await page.getByRole('checkbox', { name: 'Сыр' }).check()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('button', { name: 'Разовая проверка', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Разовая проверка' })).toBeVisible()
  await expect(page.getByText('Сыр')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Разовая проверка' })).toBeVisible()
})
