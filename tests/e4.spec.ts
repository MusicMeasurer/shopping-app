test('E4: menu is within viewport and trigger is circular', async ({ page }) => {
  await page.goto('/shopping-app/')
  const trigger = page.getByRole('button', { name: 'Действия со списком' })
  const box = await trigger.boundingBox()
  if (!box) throw new Error('Menu trigger missing')
  expect(Math.abs(box.width - box.height)).toBeLessThan(2)
  await trigger.click()
  const menu = page.getByRole('menu', { name: 'Действия со списком' })
  await expect(menu).toBeVisible()
  const rect = await menu.boundingBox()
  if (!rect) throw new Error('Menu missing')
  const viewport = page.viewportSize()
  if (!viewport) throw new Error('Viewport missing')
  expect(rect.x).toBeGreaterThanOrEqual(0)
  expect(rect.x + rect.width).toBeLessThanOrEqual(viewport.width + 1)
  expect(rect.y).toBeGreaterThanOrEqual(0)
  expect(rect.y + rect.height).toBeLessThanOrEqual(viewport.height + 1)
})

