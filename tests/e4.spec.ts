import { test, expect } from '@playwright/test'
test('E4: create, edit, archive and delete lists', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByLabel('Название списка').fill('Для поездки')
  await page.getByLabel('Тип списка').selectOption('oneoff')
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Вода\nХлеб')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Вода' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await page.getByRole('button', { name: 'Изменить Вода' }).click()
  await page.getByLabel('Количество').fill('2')
  await page.getByLabel('Единица измерения').fill('л')
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Вода · 2 л')).toBeVisible()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('button', { name: 'Для поездки' })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
  await expect(page.getByText('Вода — 2 л')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
})

