import { test, expect } from '@playwright/test'
test('E4: create, edit, archive and delete lists', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByLabel('Название списка').fill('Для поездки')
  await page.getByLabel('Тип списка').selectOption('oneoff')
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Вода\nХлеб')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Вода' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await page.getByRole('button', { name: 'Изменить Вода' }).click()
  await page.getByLabel('Количество').fill('2')
  await page.getByLabel('Единица измерения').fill('л')
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Вода · 2 л')).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Завершить список' }).click()
  await expect(page.getByRole('button', { name: 'Для поездки' })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
  await expect(page.getByText('Вода — 2 л')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для поездки' })).toBeVisible()
})

test('E4: explicit quantities survive reload; ambiguous names remain intact', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Молоко 2 л\nМука 1,5 кг\nСахар 2')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByText('Молоко · 2 л')).toBeVisible()
  await expect(page.getByText('Мука · 1.5 кг')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Сахар 2' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Молоко · 2 л')).toBeVisible()
  await expect(page.getByText('Мука · 1.5 кг')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Сахар 2' })).toBeVisible()
})

test('E4: list type changes both ways, preserves items, persists and controls completion', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByLabel('Название списка').fill('Для ремонта')
  await page.getByLabel('Тип списка', { exact: true }).selectOption('oneoff')
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Краска 2 л')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await page.getByLabel('Тип текущего списка').selectOption('permanent')
  await expect(page.getByText('Краска · 2 л')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Для ремонта' })).toBeVisible()
  await page.getByRole('button', { name: 'Для ремонта' }).click()
  await expect(page.getByLabel('Тип текущего списка')).toHaveValue('permanent')
  await expect(page.getByText('Краска · 2 л')).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Завершить список' }).click()
  await expect(page.getByRole('button', { name: 'Для ремонта' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Краска' })).toHaveCount(0)
  await page.getByLabel('Тип текущего списка').selectOption('oneoff')
  await page.reload()
  await page.getByRole('button', { name: 'Для ремонта' }).click()
  await expect(page.getByLabel('Тип текущего списка')).toHaveValue('oneoff')
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Гвозди')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Завершить список' }).click()
  await expect(page.getByRole('button', { name: 'Для ремонта' })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для ремонта' })).toHaveCount(2)
  await expect(page.getByText('Краска — 2 л')).toBeVisible()
  await expect(page.getByText('Гвозди')).toBeVisible()
})
