test('E4: list type changes both ways, preserves items, persists and controls completion', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByLabel('Название списка').fill('Для ремонта')
  await page.getByLabel('Тип списка', { exact: true }).selectOption('oneoff')
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Краска 2 л')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await page.getByRole('menuitemradio', { name: /Постоянный/ }).click()
  await expect(page.getByText('Краска · 2 л')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Для ремонта', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Для ремонта' })).toBeVisible()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await expect(page.getByRole('menuitemradio', { name: /Постоянный/ })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await expect(page.getByText('Краска · 2 л')).toBeVisible()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('button', { name: 'Для ремонта', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Краска' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await page.getByRole('menuitemradio', { name: /Разовый/ }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Для ремонта', exact: true }).click()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await expect(page.getByRole('menuitemradio', { name: /Разовый/ })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await page.getByLabel('Что нужно купить? (можно несколько строк)').fill('Гвозди')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('menuitem', { name: /Завершить список/ }).click()
  await expect(page.getByRole('button', { name: 'Для ремонта', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Архив/ }).click()
  await expect(page.getByRole('heading', { name: 'Для ремонта' })).toHaveCount(2)
  await expect(page.getByText('Краска — 2 л')).toBeVisible()
  await expect(page.getByText('Гвозди')).toBeVisible()
})

test('E4: reorder and rename persist after reload', async ({ page }) => {
  await page.goto('/shopping-app/')
  await page.getByRole('button', { name: 'Опустить список Продукты' }).click()
  await expect(page.locator('nav .list-select').first()).toContainText('Хозяйственные покупки')
  await page.reload()
  await expect(page.locator('nav .list-select').first()).toContainText('Хозяйственные покупки')
  await page.getByRole('button', { name: 'Действия со списком' }).click()
  await page.getByRole('menuitem', { name: /Переименовать/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Очистить название' }).click()
  await expect(page.getByRole('button', { name: 'Сохранить' })).toBeDisabled()
  await page.getByRole('dialog').getByLabel('Название списка').fill('Продукты на неделю')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByRole('heading', { name: 'Продукты на неделю' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Продукты на неделю', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Продукты на неделю' })).toBeVisible()
})

test('E4: long names show validation and preserve text', async ({ page }) => {
  await page.goto('/shopping-app/')
  const input = page.getByLabel('Что нужно купить? (можно несколько строк)')
  await input.fill('а'.repeat(100))
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'а'.repeat(100) })).toBeVisible()
  await input.fill('б'.repeat(121))
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.locator('.field-error')).toBeVisible()
  await expect(input).toHaveValue('б'.repeat(121))
})
