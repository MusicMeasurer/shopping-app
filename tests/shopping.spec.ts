import { test, expect } from '@playwright/test'
test('iPhone: lists, persistence, deletion and offline PWA', async ({ page, context }) => {
  await page.goto('/shopping-app/')
  const input = page.getByLabel('Что нужно купить?')
  await expect(input).toBeEnabled()
  await input.fill('Молоко')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Молоко' }).click()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await page.getByRole('button', { name: 'Хозяйственные покупки' }).click()
  await expect(page.getByText('Здесь начинается ваш список')).toBeVisible()
  await input.fill('Мыло')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Мыло' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await page.getByRole('button', { name: 'Хозяйственные покупки' }).click()
  await page.getByRole('button', { name: 'Удалить Мыло' }).click()
  await expect(page.getByText('Здесь начинается ваш список')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Хозяйственные покупки' }).click()
  await expect(page.getByText('Здесь начинается ваш список')).toBeVisible()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  const manifest = await page.request.get('/shopping-app/manifest.webmanifest')
  expect((await manifest.json()).start_url).toBe('/shopping-app/')
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).toBeChecked()
  await page.getByRole('checkbox', { name: 'Молоко' }).click()
  await input.fill('Хлеб')
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Хлеб' })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Молоко' })).not.toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('iPhone: one name per list and per batch, with independent list sorting', async ({ page }) => {
  await page.goto('/shopping-app/')
  const input = page.getByLabel('Что нужно купить?')
  const add = page.getByRole('button', { name: 'Добавить товар' })
  const sort = page.getByLabel('Сортировка')
  const names = () => page.locator('.item span').allTextContents()

  await input.fill('Мясо 2 кг\nМука 1 кг\nФасоль 1 уп.\nЯйца 10 шт.\nМорковь 5 шт.\n МУКА 3 кг')
  await add.click()
  await expect(page.getByRole('status').filter({ hasText: 'Пропущены товары' })).toContainText('МУКА')
  expect(await names()).toEqual(['Мясо · 2 кг', 'Мука · 1 кг', 'Фасоль · 1 уп.', 'Яйца · 10 шт.', 'Морковь · 5 шт.'])
  await sort.selectOption('quantity-asc')
  expect(await names()).toEqual(['Мука · 1 кг', 'Мясо · 2 кг', 'Фасоль · 1 уп.', 'Морковь · 5 шт.', 'Яйца · 10 шт.'])
  await sort.selectOption('quantity-desc')
  expect(await names()).toEqual(['Мясо · 2 кг', 'Мука · 1 кг', 'Фасоль · 1 уп.', 'Яйца · 10 шт.', 'Морковь · 5 шт.'])

  await page.getByRole('checkbox', { name: 'Мука · 1 кг' }).check()
  await input.fill('мука 7 кг')
  await add.click()
  await expect(page.getByText('В списке уже есть: мука.')).toBeVisible()
  await page.getByRole('button', { name: 'Изменить Мясо' }).click()
  const editor = page.getByRole('dialog', { name: 'Редактирование товара' })
  await editor.getByLabel('Название').fill('  МУКА  ')
  await editor.getByRole('button', { name: 'Сохранить' }).click()
  await expect(editor.getByRole('alert')).toContainText('Товар с таким названием уже есть в списке.')
  await editor.getByRole('button', { name: 'Отмена' }).click()

  await page.getByRole('button', { name: 'Хозяйственные покупки' }).click()
  await expect(sort).toHaveCount(0)
  await input.fill('Мука\nМоющее  средство')
  await add.click()
  await expect(page.getByRole('checkbox', { name: 'Мука' })).toBeVisible()
  await input.fill('моющее средство')
  await add.click()
  await expect(page.getByText('В списке уже есть: моющее средство.')).toBeVisible()
  await page.getByRole('button', { name: 'Продукты' }).click()
  await expect(sort).toHaveValue('quantity-desc')
})
