import { expect, test } from '@playwright/test'

test('opens one profile menu from settings and sorts two recent profiles before expanding', async ({ page }) => {
  await page.goto('/shopping-app/')
  const trigger = page.locator('.profile-menu-trigger')
  const panel = page.locator('#profile-menu')
  const otherProfiles = panel.locator('.profile-option > button:first-child')
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Настройки приложения' })
  await expect(settings.getByRole('group', { name: 'Локальные профили' })).toHaveCount(0)
  await settings.getByRole('button', { name: 'Настройка профиля', exact: true }).click()
  await expect(settings).toHaveCount(0)
  await expect(panel).toBeVisible()

  await panel.getByRole('button', { name: 'Изменить имя профиля' }).click()
  const rename = page.getByRole('dialog', { name: 'Имя локального профиля', exact: true })
  const input = rename.getByLabel('Имя профиля', { exact: true })
  await expect.poll(async () => (await input.boundingBox())?.width ?? 0).toBeGreaterThan(120)
  await input.fill('Домашние покупки')
  await rename.getByRole('button', { name: 'Сохранить имя' }).click()
  await expect(trigger).toContainText('Домашние покупки')

  for (let number = 2; number <= 10; number++) {
    if (!(await panel.isVisible())) await trigger.click()
    await panel.getByRole('button', { name: 'Добавить профиль', exact: true }).click()
    const nameDialog = page.getByRole('dialog', { name: 'Имя локального профиля' })
    await expect(nameDialog.getByLabel('Имя профиля', { exact: true })).toHaveValue('Локальный профиль ' + number)
    await nameDialog.getByRole('button', { name: 'Отмена' }).click()
    await expect(trigger).toContainText('Локальный профиль ' + number)
    await expect(panel).toBeHidden()
  }
  await trigger.click()
  await expect(otherProfiles).toHaveCount(2)
  await expect(panel.getByRole('button', { name: 'Добавить профиль', exact: true })).toBeDisabled()
  await panel.getByRole('button', { name: 'Ещё', exact: true }).click()
  await expect(otherProfiles).toHaveCount(9)
  await expect.poll(() => panel.locator('.profile-options').evaluate(element =>
    element.scrollHeight - element.clientHeight)).toBeGreaterThan(0)
  await otherProfiles.filter({ hasText: 'Домашние покупки' }).click()
  await expect(trigger).toContainText('Домашние покупки')
  await page.getByRole('button', { name: 'Новый список', exact: true }).click()
  await page.getByLabel('Название списка', { exact: true }).fill('Ручное изменение')
  await page.getByRole('button', { name: 'Создать', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ручное изменение', exact: true })).toBeVisible()
  await trigger.click()
  await otherProfiles.first().click()
  await expect(panel).toBeHidden()
  await trigger.click()
  await expect(otherProfiles.first()).toContainText('Домашние покупки')
  await panel.getByRole('button', { name: 'Закрыть окно аккаунта' }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
})

test('deletes an inactive profile from its row without switching the current profile', async ({ page }) => {
  await page.goto('/shopping-app/')
  const trigger = page.locator('.profile-menu-trigger')
  await expect(trigger.getByText('Локальные данные', { exact: true })).toBeVisible()
  for (let number = 2; number <= 3; number++) {
    await trigger.click()
    await page.getByRole('button', { name: 'Добавить профиль', exact: true }).click()
    const nameDialog = page.getByRole('dialog', { name: 'Имя локального профиля' })
    await expect(nameDialog.getByLabel('Имя профиля', { exact: true })).toHaveValue('Локальный профиль ' + number)
    await nameDialog.getByRole('button', { name: 'Отмена' }).click()
    await expect(trigger).toContainText('Локальный профиль ' + number)
  }
  await trigger.click()
  await expect(page.getByRole('button', { name: 'Удалить локальный профиль «Мои покупки»' })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить локальный профиль «Локальный профиль 2»' }).click()
  await page.getByRole('dialog', { name: 'Удаление профиля' }).getByRole('button', { name: 'Удалить профиль', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Удалить локальный профиль «Локальный профиль 2»' })).toHaveCount(0)
  await expect(trigger).toContainText('Локальный профиль 3')
})

test('keeps purchase history when deleting the last profile and can discard it explicitly', async ({ page }) => {
  await page.goto('/shopping-app/')
  const add = async (name: string) => {
    await page.getByLabel('Что нужно купить?', { exact: false }).fill(name)
    await page.getByRole('button', { name: 'Добавить товар' }).click()
    const item = page.getByRole('checkbox', { name, exact: true })
    await item.click()
    await expect(item).toBeChecked()
  }
  await add('Архивный хлеб')
  await page.getByRole('button', { name: 'Завершить список', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Завершить список', exact: true }).click()
  await page.getByRole('button', { name: 'Завершить: отмеченные', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Архивный хлеб' })).toHaveCount(0)
  await add('Отмеченное молоко')

  const trigger = page.locator('.profile-menu-trigger')
  const remove = page.getByRole('button', { name: 'Удалить локальный профиль «Мои покупки»' })
  const dialog = page.getByRole('dialog', { name: 'Удаление профиля' })
  await trigger.click()
  await remove.click()
  await expect(dialog).toContainText('сначала завершите отмеченные покупки')
  await expect(dialog.getByRole('button', { name: 'Оставить архив покупок' })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Отмена' }).click()
  await expect(page.getByRole('checkbox', { name: 'Отмеченное молоко' })).toBeChecked()
  await remove.click()
  await dialog.getByLabel('Куда перенести архив покупок').selectOption({ label: 'Новый локальный профиль' })
  await dialog.getByRole('button', { name: 'Оставить архив покупок' }).click()
  await expect(dialog).toHaveCount(0)
  await page.reload()
  const archive = page.getByRole('button', { name: /^Архив,/ })
  await archive.click()
  await expect(page.getByText('Архивный хлеб', { exact: true })).toBeVisible()
  await expect(page.getByText('Отмеченное молоко', { exact: true })).toHaveCount(0)

  await trigger.click()
  await remove.click()
  await dialog.getByRole('button', { name: 'Удалить архив покупок' }).click()
  await expect(dialog).toHaveCount(0)
  await archive.click()
  await expect(page.getByText('Архив пока пуст.')).toBeVisible()
})
