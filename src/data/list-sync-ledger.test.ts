import 'fake-indexeddb/auto'
import { describe, expect, it, vi } from 'vitest'
import { ListSyncLedger, type SyncWork } from './list-sync-ledger'
import { createStorage } from './storage'
import { createItem } from '../domain/shopping'

const waiting = (id: string, ...listIds: string[]): SyncWork => ({ id, listIds, kind: 'items', phase: 'waiting' })
describe('list sync state is aggregated by actual operation and scoped account', () => {
  it('gives errors priority without blocking independent lists or losing queued newer edits', () => {
    const ledger = new ListSyncLedger()
    const work = [waiting('first', 'a'), waiting('next', 'a'), waiting('other', 'b')]
    ledger.begin('one', 'first', ['a'], 'items')
    expect(ledger.states('one', work, [], 100).get('a')?.state).toBe('running')
    expect(ledger.states('one', work, [], 100).get('b')?.state).toBe('waiting')
    ledger.fail('one', 'first')
    ledger.begin('one', 'other', ['b'], 'items')
    ledger.confirm('one', 'other', ['b'], 100)
    expect(ledger.states('one', work.slice(0, 2), [], 100).get('a')?.state).toBe('error')
    expect(ledger.states('one', work.slice(0, 2), [], 100).get('b')?.state).toBe('success')
    expect(ledger.states('two', [], [], 100).size).toBe(0)
    ledger.begin('one', 'first', ['a'], 'items')
    expect(ledger.states('one', work.slice(0, 2), [], 100).get('a')?.state).toBe('running')
    ledger.confirm('one', 'first', ['a'], 110)
    ledger.reconcile('one', [work[1]])
    expect(ledger.states('one', [work[1]], [], 110).get('a')?.state).toBe('waiting')
    expect(ledger.states('one', [], [], 110).has('a')).toBe(false)
    ledger.confirm('one', 'next', ['a'], 120)
    expect(ledger.states('one', [], [], 5119).get('a')?.state).toBe('success')
    expect(ledger.states('one', [], [], 5120).has('a')).toBe(false)
  })
  it('retains a conflict during unrelated running work, handles both merge participants and ignores stale success timers', () => {
    const ledger = new ListSyncLedger()
    const q: SyncWork[] = [{ id: 'merge', listIds: ['a', 'b'], phase: 'waiting', kind: 'lists' }]
    ledger.begin('one', 'merge', ['a','b'], 'lists')
    expect(ledger.states('one', q, ['a']).get('a')?.state).toBe('error')
    expect(ledger.states('one', q, ['a']).get('b')?.state).toBe('running')
    ledger.confirm('one', 'merge', ['a','b'], 100)
    ledger.begin('one', 'new', ['a'], 'items')
    expect(ledger.states('one', [waiting('new', 'a')], [], 5100).get('a')?.state).toBe('running')
    expect(ledger.states('one', [], [], 5100).has('b')).toBe(false)
    ledger.fail('one', 'new')
    ledger.reconcile('one', [])
    expect(ledger.states('one', [], []).has('a')).toBe(false)
  })
  it('reads durable queue after restart and creates success only after committing its matching receipt', async () => {
    const name = crypto.randomUUID(), account = crypto.randomUUID(), list = crypto.randomUUID(), other = crypto.randomUUID()
    const storage = createStorage(name)
    await storage.bindAccountList(account, list, list)
    const item = createItem(list, 'Milk')
    const operation = { kind: 'cloud-add' as const, operationId: crypto.randomUUID(), localListId: list,
      remoteListId: list, itemId: item.id, item }
    await storage.saveAccountEdit(account, operation)
    expect(await storage.readListSyncWork(account)).toEqual([{ ...waiting(operation.operationId, list), itemIds: [item.id], itemChange: { operationId: operation.operationId, before: undefined, after: item, addition: true, cancelling: false, canCancel: true } }])
    expect(await storage.readListSyncWork(other)).toEqual([])
    await storage.close()
    const reopened = createStorage(name)
    const queue = await reopened.readListSyncWork(account)
    expect(reopened.listSyncLedger.states(account, queue, []).get(list)?.state).toBe('waiting')
    await reopened.claimAccountPending(account, operation.operationId)
    reopened.listSyncLedger.begin(account, operation.operationId, [list], 'items')
    expect(reopened.listSyncLedger.states(account, queue, []).get(list)?.state).toBe('running')
    await reopened.commitAccountReceipt(account, operation.operationId, list, item.id, 1)
    expect(await reopened.readListSyncWork(account)).toEqual([])
    expect(reopened.listSyncLedger.states(account, [], []).get(list)?.state).toBe('success')
    await reopened.close()
  })
  it('does not mark an empty feed or repeated unchanged revision successful', async () => {
    const storage = createStorage(crypto.randomUUID()), account = crypto.randomUUID(), list = crypto.randomUUID()
    const metadata = { id: list, ownerId: account, name: 'A', kind: 'permanent' as const, position: 0, revision: 1 }
    await storage.applyAccountFeed(account, undefined, '1', [{ entity: 'list', listId: list, metadata }], true, () => true)
    expect(storage.listSyncLedger.states(account, [], []).get(list)?.state).toBe('success')
    storage.listSyncLedger.reset(account)
    await storage.applyAccountFeed(account, '1', '1', [], false, () => true)
    await storage.applyAccountFeed(account, '1', '2', [{ entity: 'list', listId: list, metadata }], false, () => true)
    expect(storage.listSyncLedger.states(account, [], []).size).toBe(0)
    await storage.applyAccountFeed(account, '2', '3', [{ entity: 'list', listId: list, metadata: { ...metadata, name: 'B', revision: 2 } }], false, () => true)
    expect(storage.listSyncLedger.states(account, [], []).get(list)?.state).toBe('success')
    await storage.close()
  })
})
describe('indicator receipt and retry edge cases', () => {
  it('does not let an older inventory or confirmed earlier edit hide newer waiting work', () => {
    const ledger = new ListSyncLedger()
    ledger.queued('a','old',['L'],'items')
    ledger.begin('a','old',['L'],'items')
    ledger.queued('a','new',['L'],'items')
    ledger.confirm('a','old',['L'],100)
    expect(ledger.states('a',[waiting('old','L')],[],101).get('L')?.state).toBe('waiting')
    ledger.reconcile('a',[waiting('new','L')])
    ledger.begin('a','new',['L'],'items')
    ledger.confirm('a','new',['L'],200)
    expect(ledger.states('a',[waiting('new','L')],[],201).get('L')?.state).toBe('success')
  })
  it('a successful feed read cannot dismiss a failed direct write; retry is scoped', async () => {
    const ledger = new ListSyncLedger(), retry = vi.fn(async()=>{}), other = vi.fn(async()=>{})
    ledger.begin('a','meta',['L'],'lists',false)
    ledger.registerRetry('a','meta',retry)
    ledger.fail('a','meta')
    ledger.begin('a','other',['M'],'lists',false)
    ledger.registerRetry('a','other',other)
    ledger.fail('a','other')
    ledger.clearFeedErrors('a','L')
    expect(ledger.states('a',[],[]).get('L')?.state).toBe('error')
    await ledger.retryDirect('a','L',()=>true)
    expect(retry).toHaveBeenCalledOnce()
    expect(other).not.toHaveBeenCalled()
    await ledger.retryDirect('b','L',()=>true)
    expect(retry).toHaveBeenCalledOnce()
  })
})

 describe('active card separates entity scope without hiding actionable errors', () => {
  it('filters item waiting, running and receipt; list work wins while both are active', () => {
    const ledger = new ListSyncLedger()
    const state = (active?: string, now = 100) => ledger.states('a', [], [], now, active).get('L')
    ledger.queued('a','i',['L'],'items')
    expect(state('L')).toBeUndefined()
    expect(state('M')?.state).toBe('waiting')
    ledger.begin('a','i',['L'],'items')
    expect(state('L')).toBeUndefined()
    expect(state('M')?.state).toBe('running')
    ledger.begin('a','l',['L'],'lists')
    expect(state('L')?.state).toBe('running')
    ledger.confirm('a','l',['L'],100)
    expect(state('L')?.state).toBe('success')
    expect(state('M')?.state).toBe('running')
    ledger.confirm('a','i',['L'],200)
    expect(state('L',200)?.since).toBe(100)
    expect(state('M',200)?.since).toBe(200)
    expect(state('L',5100)).toBeUndefined()
    expect(state('M',5100)?.state).toBe('success')
    ledger.begin('a','i2',['L'],'items')
    ledger.fail('a','i2')
    expect(state('L',5200)).toMatchObject({state:'error',errors:['items']})
    expect(ledger.states('a',[],['L'],5200,'L').get('L')?.state).toBe('error')
  })
  it('keeps feed transport retry kind but filters by actual entity, including deferred work', () => {
    const ledger = new ListSyncLedger()
    const queued: SyncWork[] = [{id:'deferred:item',listIds:['L'],kind:'feed',scope:'items',phase:'waiting'}]
    expect(ledger.states('a',queued,[],100,'L').size).toBe(0)
    expect(ledger.states('a',queued,[],100,'M').get('L')?.state).toBe('waiting')
    ledger.begin('a','feed-i',['L'],'feed',false,'items')
    ledger.confirm('a','feed-i',['L'],100)
    expect(ledger.states('a',[],[],100,'L').size).toBe(0)
    expect(ledger.states('a',[],[],100,'M').get('L')?.state).toBe('success')
    ledger.begin('a','feed-l',['L'],'feed',false,'lists')
    ledger.confirm('a','feed-l',['L'],200)
    expect(ledger.states('a',[],[],200,'L').get('L')?.state).toBe('success')
    ledger.begin('a','feed-i2',['L'],'feed',false,'items')
    ledger.fail('a','feed-i2')
    expect(ledger.states('a',[],[],201,'L').get('L')).toMatchObject({state:'error',errors:['feed']})
  })
  it('classifies real incoming list and item changes separately', async () => {
    const storage = createStorage(crypto.randomUUID()), account = crypto.randomUUID(), list = crypto.randomUUID()
    const metadata = { id:list, ownerId:account, name:'A', kind:'permanent' as const, position:0, revision:1 }
    await storage.applyAccountFeed(account,undefined,'1',[{entity:'list',listId:list,metadata}],true,()=>true)
    expect(storage.listSyncLedger.states(account,[],[],Date.now(),list).get(list)?.state).toBe('success')
    storage.listSyncLedger.reset(account)
    const itemId = crypto.randomUUID()
    const item = {id:itemId,listId:list,name:'Milk',purchased:false,createdAt:new Date().toISOString(),version:1}
    await storage.applyAccountFeed(account,'1','2',[{entity:'item',listId:list,itemId,item}],false,()=>true)
    expect(storage.listSyncLedger.states(account,[],[],Date.now(),list).size).toBe(0)
    expect(storage.listSyncLedger.states(account,[],[],Date.now(),'other').get(list)?.state).toBe('success')
    expect(storage.listSyncLedger.itemStates(account,[],Date.now()).get(itemId)?.state).toBe('success')
    storage.listSyncLedger.reset(account)
    await storage.applyAccountFeed(account,'2','3',[{entity:'item',listId:list,itemId,item}],false,()=>true)
    expect(storage.listSyncLedger.itemStates(account,[],Date.now()).size).toBe(0)
    const otherId = crypto.randomUUID()
    await storage.applyAccountFeed(account,'3','4',[{entity:'item',listId:list,itemId:otherId,item:{...item,id:otherId}}],false,()=>true)
    expect(storage.listSyncLedger.itemStates(account,[],Date.now()).has(itemId)).toBe(false)
    expect(storage.listSyncLedger.itemStates(account,[],Date.now()).get(otherId)?.state).toBe('success')
    await storage.close()
  })
})
